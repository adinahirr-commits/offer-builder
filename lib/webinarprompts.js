  function splitBase(text){
    var cur = null, buf = {};
    String(text||"").split("\n").forEach(function(raw){
      var m = /^\s*[#*\s_>-]*מקטע\s*(\d+)\s*[–—:\-.)]?/.exec(raw);
      if(m){ cur = parseInt(m[1],10); if(!buf[cur]) buf[cur] = []; return; }
      if(cur != null) buf[cur].push(raw);
    });
    function get(n){ return (buf[n]||[]).join("\n").replace(/^\s+|\s+$/g,""); }
    var out = {};
    var hero = (get(1)+"\n"+get(2)).split("\n").map(function(l){ return l.replace(/^[#>*\s\-•]+/,"").replace(/\*\*/g,"").replace(/^\d+[.)]\s*/,"").trim(); }).filter(Boolean);
    if(hero.length >= 3){ out.w_pre = hero[0]; out.w_headline = hero[1]; out.w_without = hero[hero.length-1]; }
    else if(hero.length === 2){ out.w_headline = hero[0]; out.w_without = hero[1]; }
    else if(hero.length === 1){ out.w_headline = hero[0]; }
    if(get(3)) out.w_learn = get(3).split("\n").map(function(l){ return l.replace(/^[\s\-•*]+/,"").replace(/\*\*/g,"").trim(); }).filter(Boolean).join("\n");
    if(get(4)) out.w_problem = get(4);
    if(get(5)) out.w_forwhom = get(5);
    if(get(7)) out.w_about = get(7);
    return out;
  }

